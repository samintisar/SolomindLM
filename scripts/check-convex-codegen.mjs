/**
 * Fails when convex/_generated/api.d.ts is missing a Convex module, or still
 * lists one that is gone. Typecheck passes either way, so a PR that adds a
 * module under convex/ without running `npx convex dev` merges silently and the
 * next local codegen leaves api.d.ts dirty (#306 → #322, #331 → #337).
 *
 * Full `npx convex codegen` needs a deployment (it pushes convex.config.ts to
 * the backend to resolve components), which CI does not have. The CLI's
 * offline mode (`--system-udfs`) enumerates modules with the same code but
 * writes the pre-components template, so this script runs it, compares only
 * the module imports with the committed api.d.ts, then restores
 * convex/_generated byte for byte. Nothing is deployed and no credentials are
 * read.
 *
 * Usage: bun run check:convex-codegen
 */
import { spawnSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedDir = path.join(root, "convex", "_generated");
const apiPath = path.join(generatedDir, "api.d.ts");
const convexCli = path.join(root, "node_modules", "convex", "bin", "main.js");

// `import type * as notebooks_index from "../notebooks/index.js";`
const MODULE_IMPORT = /^import type \* as \S+ from "\.\.\/(.+)\.js";$/;

function modulePaths(source) {
  const paths = new Set();
  for (const line of source.split(/\r?\n/)) {
    const match = MODULE_IMPORT.exec(line);
    if (match) paths.add(match[1]);
  }
  return paths;
}

// Codegen writes only the top-level files; subdirectories (ai/) are left alone.
function topLevelFiles(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name);
}

function snapshot(dir) {
  return new Map(topLevelFiles(dir).map((name) => [name, readFileSync(path.join(dir, name))]));
}

function restore(dir, files) {
  for (const name of topLevelFiles(dir)) {
    if (!files.has(name)) rmSync(path.join(dir, name));
  }
  for (const [name, contents] of files) writeFileSync(path.join(dir, name), contents);
}

const committedSource = readFileSync(apiPath, "utf8");
const committed = modulePaths(committedSource);
const original = snapshot(generatedDir);

let generated;
// An empty HOME and no CONVEX_* vars keep the CLI from picking up a login or
// a deployment, so a local run behaves like CI.
const emptyHome = mkdtempSync(path.join(tmpdir(), "convex-codegen-check-"));
const env = Object.fromEntries(
  Object.entries(process.env).filter(([key]) => !key.startsWith("CONVEX_"))
);
try {
  const result = spawnSync(
    process.execPath,
    [convexCli, "codegen", "--system-udfs", "--typecheck", "disable"],
    {
      cwd: root,
      encoding: "utf8",
      env: { ...env, HOME: emptyHome, USERPROFILE: emptyHome },
      timeout: 5 * 60 * 1000,
    }
  );
  if (result.status !== 0) {
    console.error(result.stdout, result.stderr, result.error ?? "");
    console.error(`convex codegen exited with ${result.status ?? result.signal}`);
    process.exit(2);
  }
  generated = modulePaths(readFileSync(apiPath, "utf8"));
} finally {
  restore(generatedDir, original);
  rmSync(emptyHome, { recursive: true, force: true });
}

if (generated.size === 0) {
  // The template changed shape; fail loudly instead of passing on nothing.
  console.error("Parsed no module imports from the regenerated api.d.ts. Update MODULE_IMPORT.");
  process.exit(2);
}

const missing = [...generated].filter((p) => !committed.has(p)).sort();
const stale = [...committed].filter((p) => !generated.has(p)).sort();

if (missing.length === 0 && stale.length === 0) {
  console.log(`convex/_generated/api.d.ts lists all ${generated.size} Convex modules.`);
  process.exit(0);
}

for (const p of missing) console.error(`missing from api.d.ts: convex/${p}`);
for (const p of stale) console.error(`stale in api.d.ts (module is gone): convex/${p}`);
console.error(
  "\nconvex/_generated is out of date. Regenerate it against your dev deployment and commit the result:\n" +
    "  npx convex codegen\n"
);
process.exit(1);
